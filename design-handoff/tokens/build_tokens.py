"""Generate code tokens from the exported Figma variables.

Usage (from the repository root):
    python3 design-handoff/tokens/build_tokens.py

Input:  design-handoff/tokens/figma-variables.json
        (the resolved Vistara Theme and Vistara Guard variables exported from Figma)
Output: frontend/src/styles/tokens.css
        design-handoff/tokens/tokens.json  (W3C design-token format)

Each colour token is emitted twice:
    --name      the hex value
    --name-rgb  an "r g b" triplet, so Tailwind opacity modifiers work (bg-x/50)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design-handoff/tokens/figma-variables.json"
CSS = ROOT / "frontend/src/styles/tokens.css"
JSN = ROOT / "design-handoff/tokens/tokens.json"

# Added after the WCAG 1.4.11 audit: input borders need at least 3:1 against
# their surface. These values also exist as Figma variables.
EXTRA_THEME = {"border/strong": "#8C8A80"}  # 3.41:1 on bg/card
EXTRA_GUARD = {"g/border-strong": {"Night": "#6B7F71", "Day": "#7C8C81"}}  # 3.78 / 3.54


def rgb(h):
    """Convert '#RRGGBB' to 'r g b'."""
    return " ".join(str(int(h[i:i + 2], 16)) for i in (1, 3, 5))


def hsl(h):
    """Convert '#RRGGBB' to an 'h s% l%' triplet for the shadcn/ui variables."""
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
    mx, mn = max(r, g, b), min(r, g, b)
    l = (mx + mn) / 2
    if mx == mn:
        hue = s = 0.0
    else:
        d = mx - mn
        s = d / (2 - mx - mn) if l > 0.5 else d / (mx + mn)
        if mx == r:
            hue = (g - b) / d + (6 if g < b else 0)
        elif mx == g:
            hue = (b - r) / d + 2
        else:
            hue = (r - g) / d + 4
        hue *= 60
    return f"{hue:.0f} {s * 100:.0f}% {l * 100:.0f}%"


def var(name):
    """Map a token name such as 'bg/canvas' to a CSS variable name '--bg-canvas'."""
    return "--" + name.replace("/", "-")


def lines(tokens):
    out = []
    for k, v in tokens.items():
        out.append(f"  {var(k)}: {v};")
        out.append(f"  {var(k)}-rgb: {rgb(v)};")
    return out


data = json.loads(SRC.read_text())
theme = {k: v["Mode 1"] for k, v in data["Vistara Theme"].items()} | EXTRA_THEME
guard = data["Vistara Guard"] | EXTRA_GUARD

# The existing shadcn/ui components (button, input, card, ...) read these variables.
shadcn = {
    "background": "bg/canvas", "foreground": "text/primary",
    "card": "bg/card", "card-foreground": "text/primary",
    "popover": "bg/card", "popover-foreground": "text/primary",
    "primary": "brand/primary", "primary-foreground": "brand/on-primary",
    "secondary": "bg/subtle", "secondary-foreground": "text/primary",
    "muted": "bg/subtle", "muted-foreground": "text/secondary",
    "accent": "brand/tint", "accent-foreground": "brand/forest",
    "destructive": "status/danger", "destructive-foreground": "brand/on-primary",
    "border": "border/default", "input": "border/strong", "ring": "brand/primary",
}

# The same shadcn/ui variables, re-pointed at guard tokens inside the guard app,
# so shared components (Card, Input, Label, Button) render correctly in Night and Day.
shadcn_guard = {
    "background": "g/canvas", "foreground": "g/text",
    "card": "g/surface", "card-foreground": "g/text",
    "popover": "g/surface", "popover-foreground": "g/text",
    "primary": "g/accent", "primary-foreground": "g/on-accent",
    "secondary": "g/surface-2", "secondary-foreground": "g/text",
    "muted": "g/surface-2", "muted-foreground": "g/text-2",
    "accent": "g/accent-soft", "accent-foreground": "g/accent-ink",
    "destructive": "g/danger-solid", "destructive-foreground": "g/bar-text",
    "border": "g/border", "input": "g/border-strong", "ring": "g/accent",
}

css = [
    "/* Vistara design tokens. GENERATED by design-handoff/tokens/build_tokens.py",
    "   from Figma variables (file DVDO9PiDwlHtE6kqXyCIA3). Do not edit by hand. */",
    "",
    "/* Admin and Resident: Vistara Theme (single mode) */",
    ":root {",
    *lines(theme),
    "  /* shadcn/ui bridge */",
    *[f"  --{k}: {hsl(theme[v])};" for k, v in shadcn.items()],
    "  --radius: 14px;",
    "}",
    "",
    "/* Guard tablet app: Vistara Guard. Night is the default; Day is for bright sunlight. */",
    '[data-app="guard"] {',
    *lines({k: v["Night"] for k, v in guard.items()}),
    *[f"  --{k}: {hsl(guard[v]['Night'])};" for k, v in shadcn_guard.items()],
    "}",
    '[data-app="guard"][data-theme="day"] {',
    *lines({k: v["Day"] for k, v in guard.items()}),
    *[f"  --{k}: {hsl(guard[v]['Day'])};" for k, v in shadcn_guard.items()],
    "}",
    "",
]
CSS.write_text("\n".join(css))

tok = {
    "theme": {k: {"$type": "color", "$value": v} for k, v in theme.items()},
    "guard": {
        m: {k: {"$type": "color", "$value": v[m]} for k, v in guard.items()}
        for m in ("Night", "Day")
    },
}
JSN.write_text(json.dumps(tok, indent=2) + "\n")
print(f"wrote {CSS.relative_to(ROOT)} and {JSN.relative_to(ROOT)}")
